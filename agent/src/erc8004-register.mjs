// ERC-8004 Trustless-Agents registration — mint this agent's on-chain identity.
//
// ERC-8004's IdentityRegistry is an ERC-721 where tokenId = agentId and
// tokenURI = agentURI (resolves to the agent registration file — we point it at
// our agent-card.json). This script calls `register(agentURI)` and reads back the
// minted agentId from the `Registered` event.
//
// It performs a REAL on-chain transaction, so it refuses to run until you supply
// a funded wallet + the registry address. Nothing is mocked: with the env unset
// it prints what's required and exits without sending anything.
//
//   ERC8004_RPC_URL=...            EVM RPC (the chain the registry is deployed on)
//   ERC8004_REGISTRY_ADDRESS=0x... IdentityRegistry address
//   ERC8004_PRIVATE_KEY=0x...      a GAS-FUNDED key that will own the agent NFT
//   AGENT_URI=https://...          (optional) defaults to the hosted agent-card.json
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { REGISTRATION_URL, validateRegistrationFile } from "./erc8004-registration.mjs";
import { preflight, registryFor, DEFAULT_NETWORK } from "./erc8004.mjs";

// Minimal human-readable ABI (ERC-8004 IdentityRegistry, per EIP-8004).
const ABI = [
  "function register(string agentURI) returns (uint256 agentId)",
  "function setAgentURI(uint256 agentId, string newURI)",
  "function tokenURI(uint256 agentId) view returns (string)",
  "event Registered(uint256 indexed agentId, string agentURI, address indexed owner)",
];

// The agentURI a resolver will fetch. Point it at the served card, not at
// raw.githubusercontent — GitHub serves that as `text/plain`, and a resolver
// that content-sniffs will refuse a card it could otherwise read. The served
// copy carries `application/json` and `Access-Control-Allow-Origin: *`, is
// regenerated by `npm run status-list`, and is the same bytes (a test asserts
// it). This URI is written on chain and is expensive to change afterwards.
const DEFAULT_AGENT_URI = REGISTRATION_URL;

// Load agent/.env if present (does not override real env).
try {
  for (const line of readFileSync(new URL("../.env", import.meta.url), "utf8").split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
  }
} catch { /* .env optional */ }

// The chain and registry now have real defaults (the reference deployment), so
// the only thing that genuinely cannot be defaulted is the funded key.
const net = process.env.ERC8004_NETWORK || DEFAULT_NETWORK;
const known = registryFor(net);
const rpc = process.env.ERC8004_RPC_URL || known.rpc;
const registry = process.env.ERC8004_REGISTRY_ADDRESS || known.identity;
const pk = process.env.ERC8004_PRIVATE_KEY;
const agentUri = process.env.AGENT_URI || DEFAULT_AGENT_URI;

if (!pk) {
  console.log("ERC-8004 registration is not configured — nothing sent (no fake mint).");
  console.log(`Registry is known for ${net}: ${registry}`);
  console.log("The one thing that cannot be defaulted is the wallet. Set:");
  console.log("  ERC8004_PRIVATE_KEY=<gas-funded owner key>");
  console.log("Optional overrides:");
  console.log("  ERC8004_NETWORK=<known network>   ERC8004_RPC_URL=<url>   ERC8004_REGISTRY_ADDRESS=<0x…>");
  console.log(`  AGENT_URI=<registration file URI>   (default: ${DEFAULT_AGENT_URI})`);
  console.log("\nRun `npm run erc8004` to inspect the live registry without a wallet.");
  process.exit(2);
}

// Preflight before spending gas. register() against the wrong address either
// reverts (wasted fee) or succeeds against some unrelated ERC-721, which is
// worse: you get a token that is not an agent identity and no error to notice.
console.log(`Preflighting ${registry} on ${net}…`);
const report = await preflight({ rpc, address: registry });
for (const c of report.checks) console.log(`  ${c.pass ? "✅" : "❌"} ${c.name}${c.detail ? ` — ${c.detail}` : ""}`);
if (!report.ok) {
  console.error("\nRefusing to send: that address does not look like an ERC-8004 IdentityRegistry.");
  process.exit(1);
}

// The URI is written on chain. Fetch it first and check it is the document
// the spec expects — a mint that points at a 404, or at our A2A card, is a
// second transaction to fix and a token no resolver can read until then.
console.log(`Resolving ${agentUri}…`);
const res = await fetch(agentUri, { signal: AbortSignal.timeout(20_000) });
if (!res.ok) { console.error(`Refusing to send: agentURI answers HTTP ${res.status}`); process.exit(1); }
const doc = await res.json().catch(() => null);
const conformance = validateRegistrationFile(doc);
if (!conformance.valid) {
  console.error(`Refusing to send: agentURI is not an ERC-8004 registration file:\n  ${conformance.problems.join("\n  ")}`);
  process.exit(1);
}
console.log(`  ✅ resolves to a conformant registration-v1 document (${doc.services.length} services)`);

const { ethers } = await import("ethers");
const provider = new ethers.JsonRpcProvider(rpc);
const wallet = new ethers.Wallet(pk, provider);
const idRegistry = new ethers.Contract(registry, ABI, wallet);

console.log(`Registering agent on ERC-8004 IdentityRegistry ${registry}`);
console.log(`  owner   : ${wallet.address}`);
console.log(`  agentURI: ${agentUri}`);

const tx = await idRegistry.register(agentUri);
console.log(`  tx sent : ${tx.hash} — waiting for confirmation…`);
const receipt = await tx.wait();

let agentId;
for (const log of receipt.logs) {
  try {
    const parsed = idRegistry.interface.parseLog(log);
    if (parsed?.name === "Registered") { agentId = parsed.args.agentId; break; }
  } catch { /* not our event */ }
}
console.log(`✅ Registered in block ${receipt.blockNumber}. agentId = ${agentId ?? "(see Transfer event)"}`);
console.log(`  ${known.explorer}/tx/${tx.hash}`);

// Record the mint where the publish step and the card can pick it up. This is
// the one fact that only exists after the transaction, so it is written by the
// script that made it rather than typed in by hand.
if (agentId != null) {
  const out = fileURLToPath(new URL("../erc8004-minted.json", import.meta.url));
  writeFileSync(out, JSON.stringify({
    agentId: Number(agentId), network: net, registry, owner: wallet.address,
    tx: tx.hash, block: receipt.blockNumber, agentURI: agentUri,
  }, null, 2) + "\n");
  console.log(`  wrote agent/erc8004-minted.json — run \`npm run status-list\` to publish registrations[], then redeploy.`);
}
